using Microsoft.EntityFrameworkCore;

namespace Grafirio.DataAnalysis.Api.Data;

public static class DiagnosticSchema
{
    // Same additive, idempotent startup convention as SchemaPatches.
    public static void Apply(DataAnalysisDbContext db) => db.Database.ExecuteSqlRaw("""
        CREATE TABLE IF NOT EXISTS "QueryDiagnostics" (
          "Id" uuid PRIMARY KEY, "ConnectionId" uuid NOT NULL, "CompanyId" text NOT NULL,
          "QueryId" uuid NULL, "ConfigId" uuid NULL, "CreatedAt" timestamptz NOT NULL,
          "CompletedAt" timestamptz NULL, "Question" text NOT NULL, "Stage" text NOT NULL,
          "Status" text NOT NULL, "ErrorCode" text NULL, "Error" text NULL, "Model" text NOT NULL,
          "PromptVersion" text NOT NULL, "BuildVersion" text NOT NULL, "ContextHash" text NOT NULL,
          "DictionaryHash" text NOT NULL, "ContextJson" text NOT NULL, "ParametersJson" text NOT NULL,
          "EventsJson" text NOT NULL, "ReviewStatus" text NOT NULL, "ReviewNote" text NOT NULL, "DurationMs" integer NOT NULL);
        CREATE INDEX IF NOT EXISTS "IX_QueryDiagnostics_CreatedAt" ON "QueryDiagnostics" ("CreatedAt");
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_QueryDiagnostics_QueryId" ON "QueryDiagnostics" ("QueryId");
        CREATE INDEX IF NOT EXISTS "IX_QueryDiagnostics_CompanyId_ConnectionId_CreatedAt" ON "QueryDiagnostics" ("CompanyId", "ConnectionId", "CreatedAt");
        CREATE INDEX IF NOT EXISTS "IX_QueryDiagnostics_ContextHash" ON "QueryDiagnostics" ("ContextHash");
        CREATE TABLE IF NOT EXISTS "DiagnosticTestCases" (
          "Id" uuid PRIMARY KEY, "SourceId" uuid NOT NULL, "Name" text NOT NULL, "Question" text NOT NULL,
          "ContextJson" text NOT NULL, "ExpectedJson" text NOT NULL, "RunsJson" text NOT NULL,
          "CreatedAt" timestamptz NOT NULL, "LastRunAt" timestamptz NULL);
        CREATE TABLE IF NOT EXISTS "DiagnosticSettings" (
          "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "RetentionDays" integer NOT NULL,
          "RepeatedErrorThreshold" integer NOT NULL, "SlowQuerySeconds" integer NOT NULL);
        CREATE TABLE IF NOT EXISTS "DiagnosticAdminEvents" (
          "Id" uuid PRIMARY KEY, "CreatedAt" timestamptz NOT NULL, "Actor" text NOT NULL,
          "Action" text NOT NULL, "TargetId" uuid NULL, "DetailJson" text NOT NULL);
        CREATE INDEX IF NOT EXISTS "IX_DiagnosticAdminEvents_CreatedAt" ON "DiagnosticAdminEvents" ("CreatedAt");
        """);
}
